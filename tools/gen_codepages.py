#!/usr/bin/env python3
"""Generate src/text/cp_tables.c from unicode.org's Microsoft mapping files.

    python3 tools/gen_codepages.py DIR        # DIR holds the .TXT files (downloaded if missing)

Source: https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/ (PC/CP437.TXT, WINDOWS/CP1252.TXT, CP932.TXT,
CP936.TXT, CP949.TXT, CP950.TXT; PC/CP866.TXT, WINDOWS/CP1251.TXT) and ../MISC/KOI8-R.TXT (RFC 1489), Unicode
License v3 (notice in THIRD_PARTY_NOTICES.md). Chosen over WHATWG's index
files by comparing both on every byte sequence the Windows code pages define (D-007): they agree everywhere except
CP950 F9FE (Windows U+2593), and the extra WHATWG mappings (HKSCS, user-defined areas) are not what Windows writes.
"""

import hashlib
import os
import sys
import urllib.request

BASE = 'https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/'
FILES = {
    'CP437.TXT': ('PC/CP437.TXT', '6bad4dabcdf5940227c7d81fab130dcb18a77850b5d79de28b5dc4e047b0aaac'),
    'CP1252.TXT': ('WINDOWS/CP1252.TXT', 'f607ae328b4dff5e9bfef725f5fff0ae23f38797f8a5b95998a0d2735c0e8fad'),
    'CP932.TXT': ('WINDOWS/CP932.TXT', 'c9bc0b0cd42e0fbcb82a09635bb5abed86afbdd4abc9e76fa5716638217cb59f'),
    'CP936.TXT': ('WINDOWS/CP936.TXT', 'b86f601c575e9ab457380b6f7abef03c75499cc6075bdc8b4b27f3f2de74bf6a'),
    'CP949.TXT': ('WINDOWS/CP949.TXT', 'f57e6fef9d1ed44f445e319a8e1b879ce6b6064520ab571c341e47b892e32abc'),
    'CP950.TXT': ('WINDOWS/CP950.TXT', 'ed403857b05e07ecd5667c7eff6b25898cb1fefe2d06cfe718d82d631e6058b6'),
    'CP866.TXT': ('PC/CP866.TXT', 'abcc96dd4253321eb5e542c1ece3adab10df0cc20ec5d1124a0cec22d636c924'),
    'CP1251.TXT': ('WINDOWS/CP1251.TXT', 'd9d491808bd7956c26ef8ed07fa63015bfab32860720e07d5bf3a64a609927ee'),
    'KOI8-R.TXT': ('../MISC/KOI8-R.TXT', '83d73a3884a33784fc4a6b3711067ff3ea2c606b5d2e72cb326ad857d973363c'),
}


def load(d, name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        urllib.request.urlretrieve(BASE + FILES[name][0], p)
    data = open(p, 'rb').read()
    if hashlib.sha256(data).hexdigest() != FILES[name][1]:
        sys.exit('%s: SHA-256 differs from the one recorded' % name)
    m, leads = {}, set()
    for line in data.decode('latin-1').splitlines():
        if 'DBCS LEAD BYTE' in line:
            leads.add(int(line.split()[0], 16))
        f = line.split('#')[0].split()
        if len(f) >= 2 and f[0].startswith('0x') and f[1].startswith('0x'):
            m[int(f[0], 16)] = int(f[1], 16)
    for k in m:
        if k > 0xFF:
            leads.add(k >> 8)
    return m, leads


def arr(name, vals, per=16):
    rows = []
    for i in range(0, len(vals), per):
        rows.append('    ' + ','.join('0x%04X' % v for v in vals[i:i + per]) + ',')
    return 'static const uint16_t %s[%d] = {\n%s\n};\n' % (name, len(vals), '\n'.join(rows))


def main():
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    out = ['/* cp_tables.c - generated by tools/gen_codepages.py; do not edit.\n'
           ' * Data: unicode.org VENDORS/MICSFT mapping files (Unicode License v3; see THIRD_PARTY_NOTICES.md).\n'
           ' * SBCS tables: bytes 0x80..0xFF. DBCS tables: [lead 0x81..0xFE][trail 0x40..0xFE], 0 = unmapped;\n'
           ' * *_single: bytes 0x80..0xFF that are characters on their own (0 = not). */\n',
           '#include <stdint.h>\n']
    for cp, f in (('437', 'CP437.TXT'), ('1252', 'CP1252.TXT'), ('866', 'CP866.TXT'), ('1251', 'CP1251.TXT'),
                  ('koi8r', 'KOI8-R.TXT')):
        m, _ = load(d, f)
        out.append(arr('fa_cp%s' % cp, [m.get(b, 0xFFFD) for b in range(0x80, 0x100)]).replace('static const', 'const'))
    for cp in ('932', '936', '949', '950'):
        m, leads = load(d, 'CP%s.TXT' % cp)
        dbl = [m.get((l << 8) | t, 0) for l in range(0x81, 0xFF) for t in range(0x40, 0xFF)]
        single = [m.get(b, 0) if b not in leads else 0 for b in range(0x80, 0x100)]
        lead = [1 if b in leads else 0 for b in range(0x80, 0x100)]
        out.append(arr('fa_cp%s_dbcs' % cp, dbl).replace('static const', 'const'))
        out.append(arr('fa_cp%s_single' % cp, single).replace('static const', 'const'))
        out.append('const uint8_t fa_cp%s_lead[128] = {%s};\n' % (cp, ','.join(str(x) for x in lead)))
    out.append(arr('fa_cp437_t', []).replace('static const uint16_t fa_cp437_t[0] = {\n\n};\n', ''))
    s = '\n'.join(out)
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'text', 'cp_tables.c')
    open(dst, 'w').write(s)
    print('wrote', dst)


if __name__ == '__main__':
    main()
