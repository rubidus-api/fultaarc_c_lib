#!/usr/bin/env python3
"""rar15manifest.py - write tests/manifests/rar15.txt from what RAR itself extracted from the RAR 1.4 / 1.5 fixtures.

The fixtures are the fultaarc-cleanroom-rar15 room's test archives (private fixtures/rar15, see its PROVENANCE.md).
Their expected*.txt files are the room's record of RAR 1.55 (and RAR 1.40.2 for the older format) extracting them,
`archive|entry|size|crc32[|password]`; this script only reformats them:

  - the entry column becomes FultaArc's name: '\\' between folders becomes '/';
  - an archive with an entry that needs a password is left out (the manifest runner gives no RAR 1.4 password):
    tests/test_rar15.c decodes the RAR 1.4 one with its password and checks that a RAR 1.5 one is unsupported;
  - the room's known_gaps.txt (entries its decoder was known to get wrong) is not used to leave rows out: its one
    row, s0200_two.rar|A.TXT, extracts to RAR's size and CRC-32 at the room's final state (measured 2026-10-22;
    tests/test_rar15.c checks it on its own as well).

test_manifests runs the set in exact mode. Usage:

  python3 tests/tools/rar15manifest.py --fixtures ops/fixtures/rar15 > tests/manifests/rar15.txt
"""
import argparse, os, sys

SOURCES = ('expected.txt', 'expected14.txt', 'expected2.txt')


def read_rows(path):
    with open(path, encoding='ascii') as f:
        for line in f:
            line = line.rstrip('\r\n')
            if line and not line.startswith('#'):
                yield line.split('|')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fixtures', required=True)
    args = ap.parse_args()

    rows, order, excluded = {}, [], {}
    for src in SOURCES:
        for r in read_rows(os.path.join(args.fixtures, src)):
            archive, entry, size, crc = r[0], r[1], int(r[2]), r[3].lower()
            password = r[4] if len(r) > 4 else ''
            if archive not in rows:
                rows[archive] = []
                order.append(archive)
            rows[archive].append((entry.replace('\\', '/'), size, crc))
            if password:
                excluded.setdefault(archive, 'an entry needs a password')

    kept = [a for a in order if a not in excluded]
    out = sys.stdout
    out.write('# rar15.txt - RAR 1.4 / 1.5 fixtures: the fultaarc-cleanroom-rar15 room\'s test archives (private\n'
              '# fixtures/rar15, see its PROVENANCE.md). GENERATED by tests/tools/rar15manifest.py from the room\'s\n'
              '# expected*.txt: size and crc32 are those of the files RAR 1.55 (RAR 1.40.2 for the older format)\n'
              '# extracted; names with \'/\' between folders. Exact mode.\n')
    out.write('# Included: %d archives, %d files.\n' % (len(kept), sum(len(rows[a]) for a in kept)))
    out.write('# Excluded: %d archives, covered by tests/test_rar15.c:\n' % len(excluded))
    for a in order:
        if a in excluded:
            out.write('#   %s: %s\n' % (a, excluded[a]))
    for a in kept:
        for entry, size, crc in rows[a]:
            out.write('%s|%s|%d|%s\n' % (a, entry, size, crc))


if __name__ == '__main__':
    main()
