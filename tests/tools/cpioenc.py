#!/usr/bin/env python3
# cpioenc.py - a scratch cpio fixture-maker for FultaArc's cpio reader. NOT a trusted component.
#
# It builds the four cpio formats (newc 070701, crc 070702, odc 070707, old-binary) from a list of members. Each
# fixture is then validated by an INDEPENDENT reader (7z, which reads cpio) before commit - 7z extracting a
# maker-made archive back to the original bytes is what makes it a valid oracle for FultaArc's reader, independent
# of the maker. MIT, same as the project.
import struct, sys

S_IFREG = 0o100000; S_IFDIR = 0o040000

def _members_newc(members, crc):
    out = b''
    magic = b'070702' if crc else b'070701'
    def f(v): return b'%08X' % (v & 0xffffffff)
    def emit(ino, name, data, mode):
        nb = name.encode() + b'\0'
        chk = (sum(data) & 0xffffffff) if crc else 0
        h = magic + f(ino)+f(mode)+f(0)+f(0)+f(1)+f(0)+f(len(data))+f(0)+f(0)+f(0)+f(0)+f(len(nb))+f(chk)
        b = h + nb; b += b'\0' * ((-len(b)) % 4)
        b += data; b += b'\0' * ((-len(data)) % 4)
        return b
    for i, (name, data, mode) in enumerate(members): out += emit(i + 1, name, data, mode)   # unique inode per member
    nb = b'TRAILER!!!\0'
    h = magic + f(0)*11 + f(len(nb)) + f(0)
    b = h + nb; b += b'\0' * ((-len(b)) % 4)
    return out + b

def _members_odc(members):
    out = b''
    def o6(v): return b'%06o' % (v & 0o777777)
    def o11(v): return b'%011o' % (v & 0o77777777777)
    def emit(ino, name, data, mode):
        nb = name.encode() + b'\0'
        h = b'070707' + o6(0)+o6(ino)+o6(mode)+o6(0)+o6(0)+o6(1)+o6(0)+o11(0)+o6(len(nb))+o11(len(data))
        return h + nb + data
    for i, (name, data, mode) in enumerate(members): out += emit(i + 1, name, data, mode)
    nb = b'TRAILER!!!\0'
    return out + b'070707' + b'%06o'%0*7 + b'%011o'%0 + b'%06o'%len(nb) + b'%011o'%0 + nb

def _members_bin(members, be):
    e = '>' if be else '<'
    def sh(v): return struct.pack(e + 'H', v & 0xffff)
    def lg(v): return sh((v >> 16) & 0xffff) + sh(v & 0xffff)   # high word first
    out = b''
    def emit(ino, name, data, mode):
        nb = name.encode() + b'\0'
        h = sh(0o070707)+sh(0)+sh(ino)+sh(mode)+sh(0)+sh(0)+sh(1)+sh(0)+lg(0)+sh(len(nb))+lg(len(data))
        b = h + nb; b += b'\0' * (len(nb) & 1)
        b += data; b += b'\0' * (len(data) & 1)
        return b
    for i, (name, data, mode) in enumerate(members): out += emit(i + 1, name, data, mode)
    nb = b'TRAILER!!!\0'
    h = sh(0o070707)+sh(0)*7+lg(0)+sh(len(nb))+lg(0)
    b = h + nb; b += b'\0' * (len(nb) & 1)
    return out + b

def make(fmt, members):
    if fmt == 'newc': return _members_newc(members, False)
    if fmt == 'crc':  return _members_newc(members, True)
    if fmt == 'odc':  return _members_odc(members)
    if fmt == 'binle': return _members_bin(members, False)
    if fmt == 'binbe': return _members_bin(members, True)
    raise ValueError(fmt)

if __name__ == '__main__':
    # demo/self-test entry is not used by the suite; fixtures are generated by the test's own script.
    print("cpioenc: import and call make(fmt, [(name, data, mode), ...])", file=sys.stderr)
